// Module Name:   tb_door_lock_fsm
// Project:       Zynq-7000 Digital Door Lock System (PYNQ-Z2)
// Target Device: AMD Xilinx Zynq-7000 SoC (XC7Z020-1CLG400C)
//
// Description:
//   Unit testbench verifying the security finite state machine (door_lock_fsm.v).
//   Validates the primary functional scenarios required for access control:
//     1. System power-on and asynchronous reset recovery.
//     2. Sequential 4-digit passcode authentication (nominal: 1-2-3-4).
//     3. Automatic relocking mechanism upon timer expiration.
//     4. Three-strike security policy triggering persistent tamper lockout.
//
// Simulation Timing & Calibration:
//   - Clock Source: Emulates 125 MHz system clock (8.0 ns period: #4 high / #4 low).
//   - Timing Acceleration: UNLOCK_HOLD_CYCLES is scaled down from 625,000,000 cycles
//     (5.0s in hardware) to 20 cycles (160 ns in simulation) to enable rapid
//     regression verification without simulating millions of idle clock ticks.
//   - Synchronous Strobe: The task press_key emulates single-cycle pulses
//     identical to the edge-detected output of top_module and keypad_scanner.
// ============================================================================

module tb_door_lock_fsm;

    // ------------------------------------------------------------------------
    // Testbench Stimulus Signals & DUT Interconnects
    // ------------------------------------------------------------------------
    reg        clk        = 0;  // 125 MHz master clock
    reg        rst        = 0;  // Synchronous reset input
    reg        key_valid  = 0;  // Single-cycle keystroke strobe
    reg  [3:0] key_data   = 0;  // 4-bit hexadecimal key nibble
    
    // Outputs monitored from Device Under Test (DUT)
    wire       unlock_sig;      // High indicates access granted (triggers PWM servo)
    wire       alarm_sig;       // High indicates tamper lockout active
    wire [2:0] rgb_status;      // State visual telemetry: [2]=Red, [1]=Green, [0]=Blue

    // ------------------------------------------------------------------------
    // Clock Generation: 125 MHz Master Reference (Period = 8.0 ns)
    // ------------------------------------------------------------------------
    always #4 clk = ~clk;

    // ------------------------------------------------------------------------
    // Device Under Test (DUT) Instantiation
    // Parameterized with accelerated 20-cycle unlock hold window
    // ------------------------------------------------------------------------
    door_lock_fsm #(
        .UNLOCK_HOLD_CYCLES(20) // Accelerated hold window for simulation efficiency
    ) uut (
        .clk        (clk),
        .rst        (rst),
        .key_valid  (key_valid),
        .key_data   (key_data),
        .unlock_sig (unlock_sig),
        .rgb_status (rgb_status),
        .alarm_sig  (alarm_sig)
    );

    // ------------------------------------------------------------------------
    // Emulation Task: Single-Cycle Keystroke Injection
    // ------------------------------------------------------------------------
    // Accurately replicates the single-clock-cycle pulse generated by the
    // hardware edge detector in top_module and keypad_scanner.
    task press_key(input [3:0] k);
    begin
        $display("[%0t] Pressing Key: %h", $time, k);
        key_data  = k; 
        key_valid = 1;
        #8;                     // Hold strobe for exactly one 8 ns clock cycle
        key_valid = 0;          // Deassert to enforce single-cycle pulse width
        #16;                    // Inter-key settling spacing (2 full clock cycles)
    end
    endtask

    // ------------------------------------------------------------------------
    // Asynchronous Event Monitors
    // ------------------------------------------------------------------------
    always @(posedge unlock_sig) 
        $display("\n[%0t] *** SYSTEM UNLOCKED *** (rgb_status: %b - Expected Green: 010)", $time, rgb_status);

    always @(posedge alarm_sig) 
        $display("\n[%0t] !!! ALARM TRIGGERED !!! (rgb_status: %b - Security Lockout Latch)", $time, rgb_status);

    // ------------------------------------------------------------------------
    // Main Verification Scenario
    // ------------------------------------------------------------------------
    initial begin
        $display("[%0t] Starting FSM Test...", $time);

        // Phase 1: Apply initial hardware reset pulse (>2 clock periods)
        rst = 1; 
        #20; 
        rst = 0;

        // --------------------------------------------------------------------
        // Phase 2: Valid Authentication Sequence
        // Inject correct combination (1 -> 2 -> 3 -> 4) to verify state entry,
        // unlock actuation, and automatic relock upon timer exhaustion.
        // --------------------------------------------------------------------
        $display("\n[%0t] --- Testing Correct PIN (1234) ---", $time);
        press_key(4'h1); 
        press_key(4'h2); 
        press_key(4'h3); 
        press_key(4'h4);
        
